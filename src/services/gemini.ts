import { z } from 'zod';
import { GoogleGenAI, Type } from '@google/genai';
import { env } from '../config/env';
import { TavilyResult } from './tavily';

export const ArticleDigestSchema = z.object({
  title: z.string(),
  slug: z.string(),
  summary: z.string(),
  architecturalBreakdown: z.string(),
  keyTakeaways: z.array(z.string()).min(3).max(5),
  sourceUrl: z.string().url(),
  tags: z.array(z.string()),
});

export type ArticleDigest = z.infer<typeof ArticleDigestSchema>;

export class GeminiService {
  private static ai = new GoogleGenAI({ apiKey: env.GEMINI_API_KEY });

  static async synthesizeArticle(result: TavilyResult, candidateUrls: string[]): Promise<ArticleDigest> {
    const prompt = `
      You are an expert technical editor analyzing a recent article about AI developer tools, agent frameworks, or LLM infrastructure.

      Article Title: ${result.title}
      Article Content snippet: ${result.content}
      Source URL: ${result.url}

      Generate a structured digest for this article matching the required JSON schema.
      Requirements:
      - 'slug' should be URL-friendly (e.g., 'new-ai-tool-release').
      - 'architecturalBreakdown' should be in Markdown format, detailing technical specifics if available.
      - 'keyTakeaways' must be exactly 3 to 5 items.
      - 'sourceUrl' MUST exactly match the Source URL provided above (${result.url}).
      - 'tags' should be relevant keywords (e.g., 'LLM', 'Agent', 'TypeScript').
    `;

    const response = await this.ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
      config: {
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            title: { type: Type.STRING },
            slug: { type: Type.STRING },
            summary: { type: Type.STRING },
            architecturalBreakdown: { type: Type.STRING },
            keyTakeaways: {
              type: Type.ARRAY,
              items: { type: Type.STRING },
              description: "Must contain exactly 3 to 5 items"
            },
            sourceUrl: { type: Type.STRING },
            tags: {
              type: Type.ARRAY,
              items: { type: Type.STRING }
            }
          },
          required: ["title", "slug", "summary", "architecturalBreakdown", "keyTakeaways", "sourceUrl", "tags"]
        }
      }
    });

    const responseText = response.text;
    if (!responseText) {
      throw new Error('[Gemini] Empty response from model');
    }

    try {
      const parsedData = JSON.parse(responseText);
      const validatedData = ArticleDigestSchema.parse(parsedData);

      // Verify sourceUrl matches one of the candidateUrls
      if (!candidateUrls.includes(validatedData.sourceUrl)) {
        console.warn(`[Gemini] Generated sourceUrl (${validatedData.sourceUrl}) does not match any candidate URLs. Defaulting to original result URL.`);
        validatedData.sourceUrl = result.url;
      }

      return validatedData;
    } catch (error) {
      console.error('[Gemini] Failed to parse or validate generated content:', error);
      throw new Error('[Gemini] Invalid content generated by model');
    }
  }
}
